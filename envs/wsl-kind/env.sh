# shellcheck shell=bash
# ENV=wsl-kind: kind on Docker Desktop's engine (WSL2). Primary dev environment, tested in S1/S1b (plan §9).
# Contract (every envs/<ENV>/env.sh defines these): KUBE_CONTEXT, ENV_TOOLS, ENV_TESTED,
#   HARBOR_CLUSTER_IP, env_preflight, cluster_exists, cluster_create, cluster_delete, cluster_dns_apply,
#   node_mirrors_apply.
# Sourced by scripts/lib/config.sh; don't run directly.

KUBE_CONTEXT="kind-${CLUSTER_NAME}"
ENV_TOOLS="docker kind"
ENV_TESTED=yes
# Harbor's static ClusterIP, read from the env's Harbor values overlay (also used by Argo CD), so it's defined once.
HARBOR_CLUSTER_IP="$(awk '/staticClusterIP:/ {print $2}' "$ENV_DIR/values/harbor.yaml")"
export KUBE_CONTEXT ENV_TOOLS ENV_TESTED HARBOR_CLUSTER_IP

env_preflight() {
  local information memory server platform
  information=$(docker info --format '{{.MemTotal}}' 2>/dev/null) ||
    die 'Cannot connect to Docker. Check the Docker Desktop engine and this WSL distribution’s integration.'
  memory=$((information / 1024 ** 3))
  if ((information < 12 * 1024 ** 3)); then
    die "Docker has $memory GiB of RAM. Allocate at least 12 GiB in .wslconfig."
  fi
  if ((information < 16 * 1024 ** 3)); then warn "Docker has $memory GiB of RAM. 16 GiB is recommended."; fi
  server=$(docker version --format '{{.Server.Version}}' 2>/dev/null)
  platform=$(docker version --format '{{.Server.Platform.Name}}' 2>/dev/null)
  ok "Docker $server ($platform) with $memory GiB of RAM"
}

cluster_exists() {
  kind get clusters 2>/dev/null | grep -Fxq "$CLUSTER_NAME"
}

cluster_create() {
  local node_dir="$STATE_DIR/node"
  local node_image
  node_image=$(ver .cluster.kind.nodeImage) || return
  mkdir -p "$node_dir/certs.d"
  sed "s#@NODE_DIR@#$node_dir#g" "$ENV_DIR/kind.yaml" > "$node_dir/kind.yaml"
  run kind create cluster --config "$node_dir/kind.yaml" --image "$node_image" --name "$CLUSTER_NAME" --wait 120s
}

cluster_delete() {
  run kind delete cluster --name "$CLUSTER_NAME"
}

# cluster_dns_apply: make <host> resolve to <in-cluster service> for pods (plan §9.1, verified in S2). kind uses the
# kubeadm `coredns` ConfigMap, so we maintain one marked block in its Corefile. Rules come from dns_rewrites (k8s.sh).
cluster_dns_apply() {
  local cur new block
  cur="$(kc -n kube-system get cm coredns -o jsonpath='{.data.Corefile}')"
  block="    # BEGIN kubeconsandbox rewrites (managed by bootstrap)"$'\n'
  while read -r type from target; do
    block+="    rewrite stop {"$'\n'"        name $type $from $target"$'\n'"        answer auto"$'\n'"    }"$'\n'
  done < <(dns_rewrites)
  block+="    # END kubeconsandbox rewrites"
  new="$(BLK="$block" awk '
    /# BEGIN kubeconsandbox rewrites/ { skip = 1; next }
    /# END kubeconsandbox rewrites/   { skip = 0; next }
    skip { next }
    { print }
    /^ *ready$/ && !done { print ENVIRON["BLK"]; done = 1 }' <<<"$cur")"
  if [[ "$new" == "$cur" ]]; then ok "CoreDNS rewrites up to date"; return 0; fi
  run kubectl --context "$KUBE_CONTEXT" -n kube-system create configmap coredns --from-literal=Corefile="$new" \
    --dry-run=client -o yaml | run kubectl --context "$KUBE_CONTEXT" replace -f - >/dev/null
  run kubectl --context "$KUBE_CONTEXT" -n kube-system rollout restart deploy/coredns >/dev/null
  wait_rollout kube-system deploy/coredns 120s >/dev/null && ok "CoreDNS rewrites applied: $(dns_rewrites | awk '{print $2}' | tr '\n' ' ')"
}

# node_mirrors_apply: point the node's containerd at Harbor's proxy-cache projects (S2). kind reads
# /etc/containerd/certs.d, mounted from .state/node/certs.d, at pull time, so no restart is needed. The mirror uses
# Harbor's static ClusterIP (no DNS on the node); `server` falls back to upstream when Harbor is unreachable.
node_mirrors_apply() {
  local reg project _adapter url dir="$STATE_DIR/node/certs.d"
  local -A retained=(["$HARBOR_HOST"]=1)
  while read -r reg project _adapter url; do
    retained["$reg"]=1
    [[ "$reg" == docker.io ]] && url=https://registry-1.docker.io
    run mkdir -p "$dir/$reg"
    [[ "$DRY_RUN" == 1 ]] && continue
    cat >"$dir/$reg/hosts.toml" <<EOT
# Generated by bootstrap (40-harbor). Pull $reg through Harbor proxy-cache project "$project".
server = "$url"

[host."https://$HARBOR_CLUSTER_IP/v2/$project"]
  capabilities = ["pull", "resolve"]
  override_path = true
  ca = "/etc/containerd/certs.d/sandbox-ca.crt"
EOT
  done < <(registry_mirrors)
  # Harbor itself (e.g. harbor.<domain>/models/... for image volumes, L5): the node can't resolve the name (localtest.me
  # is 127.0.0.1), so pull from the static ClusterIP. Harbor names its token service after the host it's asked on.
  run mkdir -p "$dir/$HARBOR_HOST"
  [[ "$DRY_RUN" == 1 ]] || cat >"$dir/$HARBOR_HOST/hosts.toml" <<EOT
# Generated by bootstrap (40-harbor). Pull Harbor's own projects through its ClusterIP.
server = "https://$HARBOR_HOST"

[host."https://$HARBOR_CLUSTER_IP"]
  capabilities = ["pull", "resolve"]
  ca = "/etc/containerd/certs.d/sandbox-ca.crt"
EOT
  local d # remove mirror config for registries no longer in the list
  for d in "$dir"/*/; do
    [[ -d "$d" ]] || continue
    reg=$(basename "$d")
    if [[ ! ${retained[$reg]+present} ]]; then run rm -rf "$d"; fi
  done
  ok "node mirrors: $(registry_mirrors | awk '{print $1}' | tr '\n' ' ')"
}
node_mirrors_ok() {
  local reg project _adapter url
  while read -r reg project _adapter url; do
    grep -Fxq "[host.\"https://$HARBOR_CLUSTER_IP/v2/$project\"]" \
      "$STATE_DIR/node/certs.d/$reg/hosts.toml" 2>/dev/null || return 1
  done < <(registry_mirrors)
  grep -Fxq "[host.\"https://$HARBOR_CLUSTER_IP\"]" \
    "$STATE_DIR/node/certs.d/$HARBOR_HOST/hosts.toml" 2>/dev/null
}
